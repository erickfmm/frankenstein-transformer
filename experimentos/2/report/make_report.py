def n(v, dec=0):
    """Number formatted for English (comma thousands)."""
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "—"
    return f"{v:,.{dec}f}"


def ns(v, dec=0):
    """Number formatted for Spanish (dot thousands, comma decimals)."""
    if v is None or (isinstance(v, float) and not np.isfinite(v)):
        return "—"
    s = f"{v:,.{dec}f}"
    return s.replace(",", "\x00").replace(".", ",").replace("\x00", ".")


def p(v, dec=1):
    if v is None or not np.isfinite(v):
        return "—"
    return f"{v * 100:.{dec}f}%"


def ps(v, dec=1):
    if v is None or not np.isfinite(v):
        return "—"
    return f"{v * 100:.{dec}f}".replace(".", ",") + " %"


class B:
    """HTML block builder with bilingual helpers."""

    def __init__(self) -> None:
        self.parts: list[str] = []

    def add(self, html: str) -> None:
        self.parts.append(html)

    def t(self, en: str, es: str, tag: str = "span") -> str:
        return (f'<{tag} class="t-en">{en}</{tag}>'
                f'<{tag} class="t-es">{es}</{tag}>')

    def h(self, en: str, es: str, level: int = 2, anchor: str = "") -> str:
        i = f' id="{anchor}"' if anchor else ""
        return (f'<h{level}{i}>{self.t(en, es)}</h{level}>')

    def para(self, en: str, es: str, cls: str = "") -> str:
        c = f' class="{cls}"' if cls else ""
        return f'<p{c}>{self.t(en, es)}</p>'

    def callout(self, en: str, es: str, kind: str = "insight") -> str:
        return (f'<div class="callout {kind}"><span class="callout-icon">'
                f'{"◆" if kind == "insight" else "!"}</span><div>'
                f'{self.t(en, es, "div")}</div></div>')

    def figure(self, name: str, registry: list[dict]) -> str:
        meta = next(r for r in registry if r["name"] == name)
        return (
            f'<figure class="fig">'
            f'<img data-dark="img/{name}-dark.png" data-light="img/{name}-light.png" '
            f'src="img/{name}-dark.png" loading="lazy" alt="{name}">'
            f'<figcaption>{self.t(meta["en"], meta["es"])}</figcaption>'
            f'</figure>'
        )

    def table(self, df: pd.DataFrame, en_cols: list[str], es_cols: list[str],
              align: str = "left", highlight: str | None = None,
              fmt: dict | None = None) -> str:
        fmt = fmt or {}

        def render(cols: list[str]) -> str:
            head = "".join(f"<th>{c}</th>" for c in cols)
            rows = []
            for _, row in df.iterrows():
                cls = ' class="hl"' if highlight and row.iloc[0] == highlight else ""
                cells = []
                for j, c in enumerate(cols):
                    val = row.iloc[j]
                    if j in fmt:
                        cells.append(f"<td>{fmt[j](val)}</td>")
                    else:
                        cells.append(f"<td>{val}</td>")
                rows.append(f"<tr{cls}>" + "".join(cells) + "</tr>")
            return (f'<div class="table-wrap"><table class="dt"><thead><tr>{head}'
                    f'</tr></thead><tbody>{"".join(rows)}</tbody></table></div>')

        return (f'<div class="t-en">{render(en_cols)}</div>'
                f'<div class="t-es">{render(es_cols)}</div>')

    def html(self) -> str:
        return "\n".join(self.parts)


def esc(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


